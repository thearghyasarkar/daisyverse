// Regenerates docs/LETTER_V1_INDEX.md from the current archive. Used as a
// deduplication reference when writing new batches against a new source corpus.

import { build } from 'esbuild';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const tmp = await mkdtemp(path.join(tmpdir(), 'letter-index-'));
const outfile = path.join(tmp, 'letters.mjs');
await build({
  entryPoints: [path.join(ROOT, 'src/letters.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent',
});
const { LETTERS } = await import(pathToFileURL(outfile).href);
await rm(tmp, { recursive: true, force: true });

const lines = [
  '# Existing letter index',
  '',
  'A deduplication reference generated by `npm run export:letter-index`.',
  'New batches must not reuse these titles, slugs, openings, scenes, or',
  'emotional premises. Recurring private language is allowed only in a new',
  'situation grounded in a different source corpus.',
  '',
  '| ID | Title | Slug | Opening (first 12 words) | Tags |',
  '|---|---|---|---|---|',
  ...LETTERS.map(
    (l) =>
      `| ${l.id} | ${l.title.replace(/\|/g, '\\|')} | ${l.slug} | ${l.content
        .replace(/\s+/g, ' ')
        .trim()
        .split(' ')
        .slice(0, 12)
        .join(' ')
        .replace(/\|/g, '\\|')} | ${l.tags.join(', ')} |`,
  ),
  '',
];
await writeFile(path.join(ROOT, 'docs/LETTER_V1_INDEX.md'), lines.join('\n'));
console.log(`Exported ${LETTERS.length} letters to docs/LETTER_V1_INDEX.md`);
